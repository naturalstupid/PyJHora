BS_FIRST_YEAR = 1901
BS_LAST_YEAR = 2199
BS_ANCHOR_AD = _dt.date(1844, 4, 11)            # AD date of BS 1901-01-01 (Baisakh 1)
BS_MONTH_NAMES_EN = ["Baisakh", "Jestha", "Ashadh", "Shrawan", "Bhadra", "Ashwin",
                     "Kartik", "Mangsir", "Poush", "Magh", "Falgun", "Chaitra"]

# ---- derived tables (built once when the module is imported) ----
_YEAR_START = {}                                 # BS year -> ordinal of its first day (datetime.date.toordinal())
_YEAR_DAYS = {}
_MONTH_CUM = {}                                  # BS year -> [days before month 1, 2 ... 12, total]
_o = BS_ANCHOR_AD.toordinal()
for _y in range(BS_FIRST_YEAR, BS_LAST_YEAR + 1):
    _YEAR_START[_y] = _o
    _cum = [0]
    for _d in YEAR_MONTH_DAYS_BS[_y]:
        _cum.append(_cum[-1] + _d)
    _MONTH_CUM[_y] = _cum
    _YEAR_DAYS[_y] = _cum[-1]
    _o += _cum[-1]
_LAST_ORDINAL = _o - 1                           # last day of BS 2199 Chaitra
_FIRST_ORDINAL = BS_ANCHOR_AD.toordinal()
_START_SORTED = [_YEAR_START[_y] for _y in range(BS_FIRST_YEAR, BS_LAST_YEAR + 1)]


def month_days(bs_year, month):
    """Number of days of BS month `month` (1 = Baisakh ... 12 = Chaitra) of year `bs_year`."""
    return YEAR_MONTH_DAYS_BS[bs_year][month - 1]


def ad_to_bs(year, month, day):
    """Gregorian date -> (bs_year, bs_month, bs_day) with bs_month 1 = Baisakh ... 12 = Chaitra, or None when the
    date is outside the table."""
    try:
        o = _dt.date(year, month, day).toordinal()
    except (ValueError, OverflowError):
        return None
    if o < _FIRST_ORDINAL or o > _LAST_ORDINAL:
        return None
    import bisect
    y = BS_FIRST_YEAR + bisect.bisect_right(_START_SORTED, o) - 1
    n = o - _YEAR_START[y]                                   # 0-based day of the BS year
    cum = _MONTH_CUM[y]
    m = bisect.bisect_right(cum, n)                          # cum[m-1] <= n < cum[m]
    return y, m, n - cum[m - 1] + 1


def bs_to_ad(bs_year, bs_month, bs_day):
    """BS date -> datetime.date. Raises ValueError for a date that does not exist."""
    if bs_year not in _YEAR_START or not 1 <= bs_month <= 12 or not 1 <= bs_day <= month_days(bs_year, bs_month):
        raise ValueError(f"not a valid Bikram Sambat date: {bs_year}-{bs_month}-{bs_day}")
    return _dt.date.fromordinal(_YEAR_START[bs_year] + _MONTH_CUM[bs_year][bs_month - 1] + bs_day - 1)


