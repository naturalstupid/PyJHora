"""
Calculates Vimshottari (=120 year) Dasha-bhukthi-antara-sukshma-prana.

Vimshottari dasa divides a 120 year lifespan among nine planetary lords
(Ketu, Venus, Sun, Moon, Mars, Rahu, Jupiter, Saturn, Mercury) in a fixed
cyclic order, with each lord's share fixed in vimsottari_dict (which sums
to 120). Every sub-level (Mahadasa -> Antardasa -> Pratyantardasa ->
Sookshma -> Prana -> Deha) is generated by the same rule: the parent's
duration, expressed in real years, is split among the nine lords starting
from the parent lord itself and proceeding in the fixed cyclic order, in
proportion to each lord's share of 120.

This module also supports Varsha Vimshottari (Mudda dasa), the annual
compressed form of this same dasa used for Tajaka/varsha charts, where the
full 120 year lifespan is compressed into a single solar year: each unit
of a lord's 120-based share is worth (1/120) of a real year instead of a
full real year. Passing varsha_vimsottari=True to the public functions
below applies this compression at its single source -- the conversion of
each lord's share into a real-year duration -- so that every duration
throughout the dasa hierarchy is, uniformly, expressed in real years
(a tiny fraction of a year for the annual form, a whole number of years
for the natal form). jhora.horoscope.dhasa.graha.mudda is the annual-dasa
caller; it supplies its own seed lord/date (see that module) since the
annual dasa's starting lord follows a different rule than the natal
dasa's, but relies entirely on this module for generating every level of
the dasa hierarchy underneath that seed.

Every duration value returned by any public function in this module --
get_dhasa_antardhasa(), get_immediate_children(),
get_running_dhasa_for_given_date() -- is always expressed in real years,
for both natal and Varsha forms. A duration obtained from one function may
therefore always be passed unchanged into another (e.g. a row's duration
from get_dhasa_antardhasa() may be passed directly as parent_duration to
get_immediate_children()) without any additional unit conversion.
V5.0 Refactored to match JHora and added varsha_vimsottari argument to support varsha vimsottari.
"""
from collections import OrderedDict as Dict
from jhora import const, utils
""" 
    drik here is generic model name can be surya_sidhantha or drik depending on value 
    of const.astrology_model_default value
"""
drik = utils.hora_engine_proxy
from jhora.horoscope.chart import charts
year_duration = const.sidereal_year
one_star = 360 / 27.0
vimsottari_adhipati = (
    lambda nak, seed_star=3: const.vimsottari_adhipati_list[
        (nak - seed_star + 3) % (len(const.vimsottari_adhipati_list))
    ]
)
# Local copy so that tribhagi/other variations never mutate the shared library constant.
vimsottari_dict = const.vimsottari_dict.copy()
human_life_span_for_vimsottari_dhasa = const.human_life_span_for_vimsottari_dhasa
# If a freshly-computed parent end date deviates from the simple proportional
# estimate by more than this many days, the proportional estimate is used
# instead. Guards against unreliable results from very small durations.
_END_JD_SANITY_SLACK_DAYS = 30.0
### --- Vimsottari functions -------------------------------------------------
def vimsottari_next_adhipati(lord, direction=1):
    """Returns next lord after `lord` in the adhipati_list."""
    current = const.vimsottari_adhipati_list.index(lord)
    next_index = (current + direction) % len(const.vimsottari_adhipati_list)
    return const.vimsottari_adhipati_list[next_index]
def vimsottari_dasha_start_date(
    jd_at_dob,
    place,
    divisional_chart_factor=1,
    chart_method=1,
    star_position_from_moon=1,
    seed_star=3,
    dhasa_starting_planet=1,
):
    """Returns the lord and start date of the mahadasa running at birth."""
    planet_long = charts.get_chart_element_longitude(
        jd=jd_at_dob,
        place=place,
        divisional_chart_factor=divisional_chart_factor,
        chart_method=chart_method,
        star_position_from_moon=star_position_from_moon,
        dhasa_starting_planet=dhasa_starting_planet,
    )
    nak = int(planet_long / one_star)
    rem = planet_long - nak * one_star
    lord = vimsottari_adhipati(nak, seed_star)
    period = vimsottari_dict[lord]
    fraction_elapsed = rem / one_star
    start_jd = drik._get_dhasa_start_jd(jd_at_dob, place, fraction_elapsed=fraction_elapsed,
                                        total_dasa_years=period)
    return [lord, start_jd]
def vimsottari_mahadasa(
    jd_at_dob,
    place,
    divisional_chart_factor=1,
    chart_method=1,
    star_position_from_moon=1,
    seed_star=3,
    dhasa_starting_planet=1,
    seed_lord_and_start=None,
    dasa_years_scale=1.0,
):
    """
    Returns all nine mahadasa lords and their start dates for one full
    lifespan cycle, in order starting from the lord running at birth.

    seed_lord_and_start : optional (lord, start_jd) pair. When given, this
        is used directly as the first mahadasa's lord and start date
        instead of deriving it from natal Moon longitude. Used by Varsha
        Vimshottari (Mudda dasa), whose starting lord is found by
        progressing the natal seed by the number of years elapsed.
    dasa_years_scale : factor applied to each lord's 120-based share
        before it is converted into a real-year duration. 1.0 for natal
        Vimshottari (each unit = one real year); (1 / 120) for Varsha
        Vimshottari, so that the full 120 unit lifespan compresses into a
        single real year. This is the single point at which the Varsha
        compression is applied; drik._get_dhasa_end_jd() only ever
        receives an already-scaled, real-year duration.
    """
    if seed_lord_and_start is not None:
        lord, start_date = seed_lord_and_start
    else:
        lord, start_date = vimsottari_dasha_start_date(
            jd_at_dob,
            place,
            divisional_chart_factor=divisional_chart_factor,
            chart_method=chart_method,
            star_position_from_moon=star_position_from_moon,
            seed_star=seed_star,
            dhasa_starting_planet=dhasa_starting_planet,
        )
    retval = Dict()
    for _ in range(9):
        retval[lord] = start_date
        start_date = drik._get_dhasa_end_jd(
            start_jd=start_date,
            place=place,
            total_dasa_years=vimsottari_dict[lord] * dasa_years_scale,
        )
        lord = vimsottari_next_adhipati(lord)
    return retval
def _vimsottari_rasi_bhukthi(maha_lord, maha_lord_rasi, start_date, place):
    """
    Computes the twelve rasi-based bhuktis of a mahadasa, an alternate
    (sign-based, rather than lord-based) method of dividing the antardasa
    level. Valid only at the Mahadasa -> Antardasa level.
    """
    retval = Dict()
    bhukthi_duration = vimsottari_dict[maha_lord] / 12.0
    for bhukthi_rasi in [(maha_lord_rasi + h) % 12 for h in range(12)]:
        retval[bhukthi_rasi] = start_date
        start_date = drik._get_dhasa_end_jd(
            start_jd=start_date,
            place=place,
            total_dasa_years=bhukthi_duration,
        )
    return retval
def _start_lord_and_dir(parent_lord, antardhasa_option):
    """Resolves the starting lord and direction of traversal for a given antardhasa option."""
    lord = parent_lord
    if antardhasa_option in [const.ANTARDHASA_OPTION.START_FROM_NEXT_DHASA_LORD_GO_FORWARD,
                             const.ANTARDHASA_OPTION.START_FROM_NEXT_DHASA_LORD_GO_BACKWARD]:
        lord = vimsottari_next_adhipati(lord, direction=+1)
    elif antardhasa_option in [const.ANTARDHASA_OPTION.START_FROM_PREVIOUS_DHASA_LORD_GO_FORWARD,
                               const.ANTARDHASA_OPTION.START_FROM_PREVIOUS_DHASA_LORD_GO_BACKWARD]:
        lord = vimsottari_next_adhipati(lord, direction=-1)
    dirn = (+1 if antardhasa_option in [const.ANTARDHASA_OPTION.START_FROM_DHASA_LORD_GO_FORWARD,
                                       const.ANTARDHASA_OPTION.START_FROM_NEXT_DHASA_LORD_GO_FORWARD,
                                       const.ANTARDHASA_OPTION.START_FROM_PREVIOUS_DHASA_LORD_GO_FORWARD]
                else -1)
    return lord, dirn
def _child_sequence(parent_lord, antardhasa_option):
    """Returns the ordered list of the nine child lords for a given parent lord."""
    lord, dirn = _start_lord_and_dir(parent_lord, antardhasa_option)
    seq = []
    l = lord
    for _ in range(len(const.vimsottari_adhipati_list)):
        seq.append(l)
        l = vimsottari_next_adhipati(l, direction=dirn)
    return seq
### --- Child-generation engine -----------------------------------------------
def _get_children_jd(
    parent_lords,
    parent_start_jd,
    parent_duration,
    place,
    *,
    antardhasa_option=None,
    use_rasi_bhukthi_variation=False,
    divisional_chart_factor=1,
    chart_method=1,
    jd_at_dob=None,
    parent_end_jd=None,
    **kwargs,
):
    """
    Splits one dasa period among the nine planetary lords to produce the
    next level down (Mahadasa -> Antardasa, Antardasa -> Pratyantardasa,
    and so on through Deha). Used recursively for every level of the dasa,
    for both natal Vimshottari and Varsha Vimshottari (Mudda) dasa.

    parent_duration must always be expressed in real years (the same
    units as year_duration, i.e. actual elapsed time, not a raw 120-based
    share) -- for Varsha Vimshottari this is a small fraction of a year,
    for natal Vimshottari a whole number of years. It must be the clean
    cascaded value (parent's-parent duration * lord's share / 120), not a
    value derived from an already-computed calendar span.

    parent_end_jd : if the caller already knows this parent's exact end
        date (true for every level below the first), it should be passed
        in and is used as-is.
    Returns (children, parent_end_jd) where children is a list of
    (child_lords_tuple, child_start_jd, child_end_jd, child_duration_years).
    """
    if antardhasa_option is None: antardhasa_option = const.antardhasa_option_default
    global year_duration, human_life_span_for_vimsottari_dhasa, vimsottari_dict
    parent_lord = parent_lords[-1]
    H = float(human_life_span_for_vimsottari_dhasa)
    if parent_end_jd is None:
        candidate_end_jd = drik._get_dhasa_end_jd(
            start_jd=parent_start_jd,
            place=place,
            total_dasa_years=float(parent_duration),
        )
        expected_span_days = float(parent_duration) * year_duration
        actual_span_days = candidate_end_jd - parent_start_jd
        if abs(actual_span_days - expected_span_days) > _END_JD_SANITY_SLACK_DAYS:
            parent_end_jd = parent_start_jd + expected_span_days
        else:
            parent_end_jd = candidate_end_jd
    # Rasi bhukthi variation applies only at the Mahadasa -> Antardasa level.
    if use_rasi_bhukthi_variation and len(parent_lords) == 1:
        if jd_at_dob is None:
            raise ValueError("jd is required for rasi-bhukthi variation at the MD->AD level.")
        planet_positions = charts.divisional_chart(
            jd_at_dob, place, divisional_chart_factor=divisional_chart_factor,
        )
        maha_lord_rasi = planet_positions[parent_lord + 1][1][0]
        rasi_bhuktis = _vimsottari_rasi_bhukthi(
            parent_lord, maha_lord_rasi, parent_start_jd, place,
        )
        items = list(rasi_bhuktis.items())
        clean_child_duration = float(parent_duration) / 12.0
        children = []
        for idx, (child_lord, child_start_jd) in enumerate(items):
            child_end_jd = parent_end_jd if idx == len(items) - 1 else items[idx + 1][1]
            children.append(
                (parent_lords + (child_lord,), child_start_jd, child_end_jd, clean_child_duration)
            )
        return children, parent_end_jd
    # Standard case: proportional division among the nine planetary lords.
    sequence = _child_sequence(parent_lord, antardhasa_option)
    child_durations = [float(parent_duration) * float(vimsottari_dict[l]) / H for l in sequence]
    total_child_years = sum(child_durations) or 1.0
    span = parent_end_jd - parent_start_jd
    min_child_days = min(child_durations) * year_duration
    children = []
    if min_child_days >= 1.0:
        # Each child boundary of at least a day is computed via the true
        # solar-arc dasa calculation, chained from the previous boundary.
        # The final child is always clamped to the parent's end date.
        jd_cursor = parent_start_jd
        remaining_years = total_child_years
        for idx, (clord, cdur) in enumerate(zip(sequence, child_durations)):
            if idx == len(sequence) - 1:
                child_end_jd = parent_end_jd
            else:
                child_end_jd = drik._get_dhasa_end_jd(
                    start_jd=jd_cursor, place=place, total_dasa_years=cdur,
                )
                if not (jd_cursor < child_end_jd < parent_end_jd):
                    frac = cdur / remaining_years if remaining_years > 0 else 0.0
                    child_end_jd = jd_cursor + (parent_end_jd - jd_cursor) * frac
            children.append((parent_lords + (clord,), jd_cursor, child_end_jd, cdur))
            jd_cursor = child_end_jd
            remaining_years -= cdur
    else:
        # For very short child periods, divide the already-known parent span
        # proportionally rather than computing each boundary independently.
        cum = 0.0
        for idx, (clord, cdur) in enumerate(zip(sequence, child_durations)):
            cstart = parent_start_jd + span * (cum / total_child_years)
            cum += cdur
            cend = parent_end_jd if idx == len(sequence) - 1 else parent_start_jd + span * (cum / total_child_years)
            children.append((parent_lords + (clord,), cstart, cend, cdur))
    if children:
        last = children[-1]
        children[-1] = (last[0], last[1], parent_end_jd, last[3])
    return children, parent_end_jd
def get_immediate_children(
    parent_lords,
    parent_start,
    parent_duration=None,
    parent_end=None,
    *,
    antardhasa_option=None,
    use_rasi_bhukthi_variation=False,
    jd_at_dob=None,
    place=None,
    divisional_chart_factor=1,
    chart_method=1,
    dhasa_duration_type=None,
    savana_year_method=None,
    **kwargs,
):
    """
    Returns the immediate children of one dasa period, one level down.
    Provide exactly one of parent_duration (in real years) or parent_end
    (an exact end date); when parent_end is given, the parent's real-year
    duration is derived from the actual elapsed time between parent_start
    and parent_end. parent_duration, when given directly, must always be
    expressed in real years -- the same single convention used throughout
    this module for both natal Vimshottari and Varsha Vimshottari (Mudda)
    dasa -- so a duration value returned by get_dhasa_antardhasa() above,
    or by jhora.horoscope.dhasa.graha.mudda, can be passed back in here
    unchanged, regardless of which form of the dasa it came from.
    """
    if antardhasa_option is None: antardhasa_option = const.antardhasa_option_default
    global year_duration
    if jd_at_dob is not None and place is not None:
        year_duration = float(drik.dhasa_year_duration(
            jd=jd_at_dob,
            place=place,
            dhasa_duration_type=dhasa_duration_type,
            savana_year_method=savana_year_method,
        ))
    if isinstance(parent_lords, int):
        path = (parent_lords,)
    elif isinstance(parent_lords, (list, tuple)):
        if len(parent_lords) == 0:
            raise ValueError("parent_lords cannot be empty")
        path = tuple(parent_lords)
    else:
        raise TypeError("parent_lords must be int or tuple/list of ints")
    start_jd = utils._tuple_to_jd(parent_start)
    if (parent_duration is None) == (parent_end is None):
        raise ValueError("Provide exactly one of parent_duration (years) or parent_end (tuple).")
    known_end_jd = None
    if parent_end is None:
        clean_duration = float(parent_duration)
    else:
        known_end_jd = utils._tuple_to_jd(parent_end)
        if known_end_jd <= start_jd:
            return []
        clean_duration = (known_end_jd - start_jd) / year_duration
    children, _parent_end_jd = _get_children_jd(
        parent_lords=path,
        parent_start_jd=start_jd,
        parent_duration=clean_duration,
        place=place,
        antardhasa_option=antardhasa_option,
        use_rasi_bhukthi_variation=use_rasi_bhukthi_variation,
        divisional_chart_factor=divisional_chart_factor,
        chart_method=chart_method,
        jd_at_dob=jd_at_dob,
        parent_end_jd=known_end_jd,
        **kwargs
    )
    return [
        [lords, utils._jd_to_tuple(start_jd_c), utils._jd_to_tuple(end_jd_c)]
        for (lords, start_jd_c, end_jd_c, _dur) in children
    ]
def _expand_all_levels(
    parent_lords,
    parent_start_jd,
    parent_end_jd,
    parent_duration,
    target_depth,
    place,
    *,
    antardhasa_option,
    use_rasi_bhukthi_variation,
    divisional_chart_factor,
    chart_method,
    jd_at_dob,
    emit_row,
    **kwargs,
):
    """
    Recursively expands a dasa hierarchy from `parent_lords` down to
    `target_depth`, emitting one row per leaf node at that depth.

    target_depth : the depth at which rows should be emitted (2 for
        mahadasa-bhukti, 3 for mahadasa-bhukti-antara, and so on).
    emit_row : callback invoked as emit_row(lords_tuple, start_jd, end_jd, duration_years).
    """
    depth = len(parent_lords)
    if depth == target_depth:
        emit_row(parent_lords, parent_start_jd, parent_end_jd, parent_duration)
        return
    use_rasi_here = use_rasi_bhukthi_variation and depth == 1
    children, _parent_end_jd_confirmed = _get_children_jd(
        parent_lords=parent_lords,
        parent_start_jd=parent_start_jd,
        parent_duration=parent_duration,
        place=place,
        antardhasa_option=antardhasa_option,
        use_rasi_bhukthi_variation=use_rasi_here,
        divisional_chart_factor=divisional_chart_factor,
        chart_method=chart_method,
        jd_at_dob=jd_at_dob,
        parent_end_jd=parent_end_jd,
        **kwargs,
    )
    for (child_lords, child_start_jd, child_end_jd, child_duration) in children:
        _expand_all_levels(
            child_lords,
            child_start_jd,
            child_end_jd,
            child_duration,
            target_depth,
            place,
            antardhasa_option=antardhasa_option,
            use_rasi_bhukthi_variation=use_rasi_bhukthi_variation,
            divisional_chart_factor=divisional_chart_factor,
            chart_method=chart_method,
            jd_at_dob=jd_at_dob,
            emit_row=emit_row,
            **kwargs,
        )
def get_dhasa_antardhasa(
    dob, tob,
    place,
    star_position_from_moon=1,
    use_tribhagi_variation=False,
    use_rasi_bhukthi_variation=False,
    divisional_chart_factor=1,
    chart_method=1,
    seed_star=3,
    antardhasa_option=None,
    dhasa_starting_planet=1,
    dhasa_level_index=const.MAHA_DHASA_DEPTH.ANTARA,
    dhasa_duration_type=None,
    savana_year_method=None,
    return_exact_bounds=False,
    varsha_vimsottari=False,
    seed_lord_and_start=None,
):
    """
    Provides Vimsottari dhasa at the selected depth for a given birth date
    and time.
    RETURNS (default, return_exact_bounds=False):
        (vim_balance, [ (lords_tuple, (Y, M, D, fractional_hour), duration_years_float), ... ])
    RETURNS (return_exact_bounds=True):
        (vim_balance, [ (lords_tuple, start_jd_float, end_jd_float, duration_years_float), ... ])
    In both cases, duration_years_float is always expressed in real years
    (multiply by the real year length in days to get the duration in
    days) -- a whole-number-scale value for natal Vimshottari, a small
    fraction of a year for Varsha Vimshottari.

    dhasa_level_index : 1..6 (1=Maha, 2=Antara, 3=Pratyantara, 4=Sookshma,
        5=Prana, 6=Deha). Every level from 2 through 6 is generated by the
        same recursive division of the parent period among the nine lords.

    varsha_vimsottari : set True for Varsha Vimshottari (Mudda dasa). This
        compresses the 120 unit lifespan into one real year by scaling
        each lord's share by (1/120) at the point it is converted into a
        real-year duration; every level below inherits this compression
        automatically since each level's duration is a proportional share
        of its parent's already-real-year duration. jhora.horoscope.dhasa.
        graha.mudda is the intended caller for this, supplying its own
        seed_lord_and_start.
    seed_lord_and_start : optional (lord, start_jd) override forwarded to
        vimsottari_mahadasa(). When None, the seed is derived from natal
        Moon longitude as usual.
    """
    utils.validate_star_index(seed_star)
    if antardhasa_option is None: antardhasa_option = const.antardhasa_option_default
    global human_life_span_for_vimsottari_dhasa, vimsottari_dict, year_duration
    if not (1 <= dhasa_level_index <= 6):
        raise ValueError("dhasa_level_index must be in 1..6 (1=Maha .. 6=Deha).")
    jd = utils.julian_day_number(dob,tob)
    year_duration = float(drik.dhasa_year_duration(
        jd=jd,
        place=place,
        dhasa_duration_type=dhasa_duration_type,
        savana_year_method=savana_year_method,
    ))
    _orig_H = human_life_span_for_vimsottari_dhasa
    _orig_dict = vimsottari_dict.copy()
    try:
        _working_dict = _orig_dict
        if use_tribhagi_variation:
            _trib = 1.0 / 3.0
            H = _orig_H * _trib
            _working_dict = {k: round(v * _trib, 6) for k, v in _orig_dict.items()}
            _dhasa_cycles = int(1 / _trib)
        else:
            H = _orig_H
            _dhasa_cycles = 1
        human_life_span_for_vimsottari_dhasa = H
        vimsottari_dict = _working_dict
        # dasa_years_scale converts a lord's H-based share into a real-year
        # duration: 1.0 for natal Vimshottari (each unit = one real year);
        # (1/H) for Varsha Vimshottari, compressing the whole H-unit
        # lifespan into a single real year. This is the single point where
        # the Varsha compression is applied; every level below cascades
        # proportionally from this already-real-year value.
        dasa_years_scale = (1.0 / H) if varsha_vimsottari else 1.0
        dashas = vimsottari_mahadasa(
            jd,
            place,
            divisional_chart_factor=divisional_chart_factor,
            chart_method=chart_method,
            star_position_from_moon=star_position_from_moon,
            seed_star=seed_star,
            dhasa_starting_planet=dhasa_starting_planet,
            seed_lord_and_start=seed_lord_and_start,
            dasa_years_scale=dasa_years_scale,
        )
        dl = list(dashas.values())
        de = dl[1]
        y, m, d, _ = utils.jd_to_gregorian(jd)
        p_date1 = drik.Date(y, m, d)
        y, m, d, _ = utils.jd_to_gregorian(de)
        p_date2 = drik.Date(y, m, d)
        vim_bal = utils.panchanga_date_diff(p_date1, p_date2)
        dhasa_bhukthi = []
        def _emit_row(lords_tuple, start_jd, end_jd, duration_years):
            if return_exact_bounds:
                dhasa_bhukthi.append(
                    [lords_tuple, start_jd, end_jd, float(duration_years)]
                )
            else:
                dhasa_bhukthi.append(
                    [lords_tuple, utils.jd_to_gregorian(start_jd), float(duration_years)]
                )
        total_lords = len(const.vimsottari_adhipati_list)
        first_lord, first_start_jd = next(iter(dashas.items()))
        md_sequence = []
        cur_lord, cur_start_jd = first_lord, first_start_jd
        for _ in range(_dhasa_cycles * total_lords):
            cur_years = float(vimsottari_dict[cur_lord]) * dasa_years_scale
            cur_end_jd = drik._get_dhasa_end_jd(
                start_jd=cur_start_jd, place=place, total_dasa_years=cur_years,
            )
            md_sequence.append((cur_lord, cur_start_jd, cur_end_jd, cur_years))
            cur_start_jd = cur_end_jd
            cur_lord = vimsottari_next_adhipati(cur_lord)

        for (md_lord, md_start_jd, md_end_jd, md_years) in md_sequence:
            if dhasa_level_index == const.MAHA_DHASA_DEPTH.MAHA_DHASA_ONLY:
                _emit_row((md_lord,), md_start_jd, md_end_jd, md_years)
                continue
            if use_rasi_bhukthi_variation and dhasa_level_index > const.MAHA_DHASA_DEPTH.ANTARA:
                raise ValueError(
                    "L3+ not supported with use_rasi_bhukthi_variation=True. "
                    "Keep depth at L2 or specify a custom L3/L4 rule."
                )
            _expand_all_levels(
                (md_lord,), md_start_jd, md_end_jd, md_years, dhasa_level_index, place,
                antardhasa_option=antardhasa_option, use_rasi_bhukthi_variation=use_rasi_bhukthi_variation,
                divisional_chart_factor=divisional_chart_factor, chart_method=chart_method,
                jd_at_dob=jd, emit_row=_emit_row,
            )
        return vim_bal, dhasa_bhukthi
    finally:
        human_life_span_for_vimsottari_dhasa = _orig_H
        vimsottari_dict = _orig_dict
def get_running_dhasa_for_given_date(
    current_jd,
    jd_at_dob,
    place,
    dhasa_level_index=6,
    *,
    dhasa_duration_type=None,
    savana_year_method=None,
    varsha_vimsottari=False,
    seed_lord_and_start=None,
    **kwargs,
):
    """
    Finds the running dasa at the requested depth for a given date.
    Returns the full running ladder:
        [ [lords_tuple, start_tuple, end_tuple], ... ]  (one row per level)

    varsha_vimsottari / seed_lord_and_start : see get_dhasa_antardhasa().
    """
    global year_duration
    year_duration = float(drik.dhasa_year_duration(
        jd=jd_at_dob,
        place=place,
        dhasa_duration_type=dhasa_duration_type,
        savana_year_method=savana_year_method,
    ))
    try:
        target_depth = int(dhasa_level_index)
    except Exception:
        target_depth = 6
    target_depth = max(1, min(6, target_depth))
    antardhasa_option = kwargs.pop("antardhasa_option", const.antardhasa_option_default)
    use_rasi_bhukthi_variation = kwargs.pop("use_rasi_bhukthi_variation", False)
    divisional_chart_factor = kwargs.pop("divisional_chart_factor", 1)
    chart_method = kwargs.pop("chart_method", 1)
    star_position_from_moon = kwargs.pop("star_position_from_moon", 1)
    seed_star = kwargs.pop("seed_star", 3)
    dhasa_starting_planet = kwargs.pop("dhasa_starting_planet", 1)
    dasa_years_scale = (1.0 / float(human_life_span_for_vimsottari_dhasa)) if varsha_vimsottari else 1.0
    # Level 1: find the running Mahadasa.
    dashas = vimsottari_mahadasa(
        jd_at_dob,
        place,
        divisional_chart_factor=divisional_chart_factor,
        chart_method=chart_method,
        star_position_from_moon=star_position_from_moon,
        seed_star=seed_star,
        dhasa_starting_planet=dhasa_starting_planet,
        seed_lord_and_start=seed_lord_and_start,
        dasa_years_scale=dasa_years_scale,
    )
    md_items = list(dashas.items())
    md_lord, md_start_jd = md_items[0]
    md_end_jd_known = None
    for idx, (lord, start_jd) in enumerate(md_items):
        next_start_jd = md_items[idx + 1][1] if idx < len(md_items) - 1 else None
        if start_jd <= current_jd and (next_start_jd is None or current_jd < next_start_jd):
            md_lord, md_start_jd = lord, start_jd
            md_end_jd_known = next_start_jd
            break
    md_years = float(vimsottari_dict[md_lord]) * dasa_years_scale
    running_all = []
    _, md_end_jd = _get_children_jd(
        (md_lord,), md_start_jd, md_years, place,divisional_chart_factor=divisional_chart_factor,
        antardhasa_option=antardhasa_option, jd_at_dob=jd_at_dob,chart_method=chart_method,
        parent_end_jd=md_end_jd_known,
        **kwargs,
    )
    running_all.append([(md_lord,), md_start_jd, md_end_jd])
    if target_depth == const.MAHA_DHASA_DEPTH.MAHA_DHASA_ONLY:
        return [
            [lords, utils._jd_to_tuple(s), utils._jd_to_tuple(e)] for (lords, s, e) in running_all
        ]
    # Levels 2..target_depth: descend one level at a time, keeping the
    # child whose span contains current_jd at each level.
    parent_lords = (md_lord,)
    parent_start_jd = md_start_jd
    parent_duration = md_years
    parent_end_jd = md_end_jd
    for depth in range(2, target_depth + 1):
        use_rasi_here = use_rasi_bhukthi_variation and len(parent_lords) == 1
        children, parent_end_jd = _get_children_jd(
            parent_lords=parent_lords,
            parent_start_jd=parent_start_jd,
            parent_duration=parent_duration,
            place=place,
            antardhasa_option=antardhasa_option,
            use_rasi_bhukthi_variation=use_rasi_here,
            divisional_chart_factor=divisional_chart_factor,
            jd_at_dob=jd_at_dob,
            parent_end_jd=parent_end_jd,
            **kwargs,
        )
        running_all[-1][2] = parent_end_jd
        if not children:
            raise ValueError("No children generated; check parent span or child generator options.")
        chosen = children[-1]
        for child in children:
            _, cstart, cend, _cdur = child
            if cstart <= current_jd < cend:
                chosen = child
                break
        child_lords, child_start_jd, child_end_jd, child_duration = chosen
        running_all.append([child_lords, child_start_jd, child_end_jd])
        parent_lords = child_lords
        parent_start_jd = child_start_jd
        parent_duration = child_duration
        parent_end_jd = child_end_jd
    return [
        [lords, utils._jd_to_tuple(s), utils._jd_to_tuple(e)] for (lords, s, e) in running_all
    ]
def nakshathra_dhasa_progression(
    jd_at_dob,
    place,
    jd_current,
    star_position_from_moon=1,
    use_tribhagi_variation=False,
    divisional_chart_factor=1,
    chart_method=1,
    seed_star=3,
    antardhasa_option=None,
    dhasa_starting_planet=1,
    dhasa_level_index=const.MAHA_DHASA_DEPTH.ANTARA,
    get_running_dhasa=True,
    dhasa_duration_type=None,
    savana_year_method=None,
    **kwargs,
):
    utils.validate_star_index(seed_star)
    if antardhasa_option is None: antardhasa_option = const.antardhasa_option_default
    DLI = dhasa_level_index
    y,m,d,fh = utils.jd_to_gregorian(jd_at_dob)
    dob = drik.Date(y,m,d); tob = (fh,0,0)
    _,vd = get_dhasa_antardhasa(
        dob,tob,
        place,
        divisional_chart_factor=divisional_chart_factor,
        chart_method=chart_method,
        star_position_from_moon=star_position_from_moon,
        use_tribhagi_variation=use_tribhagi_variation,
        antardhasa_option=antardhasa_option,
        dhasa_starting_planet=dhasa_starting_planet,
        seed_star=seed_star,
        dhasa_level_index=DLI,
        dhasa_duration_type=dhasa_duration_type,
        savana_year_method=savana_year_method,
        **kwargs,
    )

    vdc = None

    if get_running_dhasa:
        vd_for_utils = [(row[0], row[1]) for row in vd]
        vdc = utils.get_running_dhasa_for_given_date(jd_current, vd_for_utils)

    jds = [
        utils.julian_day_number(drik.Date(row[1][0], row[1][1], row[1][2]), (row[1][3], 0, 0))
        for row in vd
    ]

    planet_long = charts.get_chart_element_longitude(
        jd_at_dob,
        place,
        divisional_chart_factor=1,
        chart_method=chart_method,
        star_position_from_moon=star_position_from_moon,
        dhasa_starting_planet=dhasa_starting_planet,
    )

    birth_star_index = int((planet_long % 360.0) // utils.ONE_NAK)

    prog_long = utils.progressed_abs_long_general(
        jds,
        jd_current,
        birth_star_index,
        dhasa_level_index=DLI,
        total_lords_in_dhasa=len(const.vimsottari_adhipati_list),
    )

    progression_correction = (prog_long - planet_long) % 360

    if get_running_dhasa:
        return progression_correction, vdc

    return progression_correction

